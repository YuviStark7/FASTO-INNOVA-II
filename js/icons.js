function lucide(name, size) {
  var body = LUCIDE[name] || "";
  var px = size || 18;
  return '<svg class="lucide lucide-' + name + '" xmlns="http://www.w3.org/2000/svg" width="' + px + '" height="' + px + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + body + '</svg>';
}
// Fills every <span data-icon="name" [data-size="16"]> in the page.
function paintIcons(root) {
  var scope = root || document;
  if (!scope.querySelectorAll) return;
  scope.querySelectorAll("[data-icon]").forEach(function (el) {
    el.innerHTML = lucide(el.getAttribute("data-icon"), Number(el.getAttribute("data-size")) || 18);
  });
}
if (typeof document !== "undefined" && document.addEventListener) {
  document.addEventListener("DOMContentLoaded", function () { paintIcons(); });
}
if (typeof module !== "undefined" && module.exports) module.exports = { LUCIDE: LUCIDE, lucide: lucide };
